# setup-cloudflared.ps1 -- expose the game on YOUR OWN domain via Cloudflare Tunnel.
#
# Why this exists: Tailscale Funnel gives a permanent URL but the domain is
# always *.ts.net and custom domains are NOT supported (feature request still open).
# Cloudflare Tunnel does support custom domains, and we verified on 2026-09-27 that
# this network CAN now reach the Cloudflare edge (both QUIC/UDP and HTTP2/TCP pass,
# and SSE streaming is NOT buffered: first byte ~0.9s, chunks arrive incrementally).
#
# What YOU must do first (cannot be automated -- needs your account and payment):
#   1. Buy a domain (any registrar). A .top/.xyz first year is often a few CNY;
#      a .com is ~10 USD/year. Renewal price matters more than year-one price.
#   2. Add that domain to Cloudflare (free plan) and change its nameservers at the
#      registrar to the two Cloudflare gives you. Wait until Cloudflare says "Active".
#   3. Run once, in a normal window:   cloudflared tunnel login
#      Pick the domain in the browser page that opens. This writes
#      %USERPROFILE%\.cloudflared\cert.pem -- everything below depends on it.
#
# Then run:
#   powershell -ExecutionPolicy Bypass -File setup-cloudflared.ps1 -Domain court.example.com
#
# ASCII-only on purpose: powershell.exe reads BOM-less UTF-8 as ANSI and would
# mangle any non-ASCII characters in this file.
param(
  [Parameter(Mandatory = $true)][string]$Domain,
  [string]$TunnelName = 'gangjing-court'
)

$ErrorActionPreference = 'Stop'
$Root     = $PSScriptRoot
$Cf       = Join-Path (Split-Path -Parent $Root) 'tools\cloudflared.exe'
$Port     = 8790
$ConfDir  = Join-Path $env:USERPROFILE '.cloudflared'
$CertFile = Join-Path $ConfDir 'cert.pem'
$ConfFile = Join-Path $ConfDir 'config.yml'

function Say([string]$m) { Write-Host $m }

if (-not (Test-Path $Cf)) { Say "MISSING cloudflared: $Cf"; exit 1 }

# ---- 0. sanity check the hostname -------------------------------------
if ($Domain -notmatch '^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$') {
  Say "That does not look like a hostname: $Domain"
  Say "Expected something like court.example.com (lowercase, no http://, no trailing slash)."
  exit 1
}

# ---- 1. must be logged in ---------------------------------------------
if (-not (Test-Path $CertFile)) {
  Say "Not logged in yet. Run this once in a normal window, then re-run this script:"
  Say "    `"$Cf`" tunnel login"
  exit 1
}
Say "OK  found login cert: $CertFile"

# ---- 2. create (or reuse) the named tunnel ----------------------------
Say "Looking for an existing tunnel named '$TunnelName' ..."
$listJson = & $Cf tunnel list --output json 2>$null | Out-String
$tunnelId = $null
try {
  $list = $listJson | ConvertFrom-Json
  $hit = $list | Where-Object { $_.name -eq $TunnelName } | Select-Object -First 1
  if ($hit) { $tunnelId = $hit.id }
} catch { }

if ($tunnelId) {
  Say "OK  reusing tunnel '$TunnelName'  id=$tunnelId"
} else {
  Say "Creating tunnel '$TunnelName' ..."
  & $Cf tunnel create $TunnelName | ForEach-Object { Say "    $_" }
  $listJson = & $Cf tunnel list --output json 2>$null | Out-String
  $list = $listJson | ConvertFrom-Json
  $hit = $list | Where-Object { $_.name -eq $TunnelName } | Select-Object -First 1
  if (-not $hit) { Say "FAILED to create the tunnel. Output above may say why."; exit 1 }
  $tunnelId = $hit.id
  Say "OK  created  id=$tunnelId"
}

$credFile = Join-Path $ConfDir "$tunnelId.json"
if (-not (Test-Path $credFile)) { Say "MISSING credentials file: $credFile"; exit 1 }

# ---- 3. write config.yml ---------------------------------------------
# Forward slashes on purpose: backslashes inside YAML strings are escape chars.
$credYaml = $credFile.Replace('\', '/')
$yaml = @"
# Generated by setup-cloudflared.ps1 -- safe to re-run, it just rewrites this file.
tunnel: $tunnelId
credentials-file: $credYaml

# Longer timeouts than the defaults: a single trial can take ~6s per model call
# and the SSE stream can stay open for tens of seconds.
ingress:
  - hostname: $Domain
    service: http://127.0.0.1:$Port
    originRequest:
      connectTimeout: 30s
      noHappyEyeballs: true
  - service: http_status:404
"@
Set-Content -Path $ConfFile -Value $yaml -Encoding UTF8
Say "OK  wrote $ConfFile"

# ---- 4. point DNS at the tunnel --------------------------------------
Say "Routing DNS $Domain -> tunnel ..."
& $Cf tunnel route dns $TunnelName $Domain | ForEach-Object { Say "    $_" }

# ---- 5. tell the user what happens next ------------------------------
Say ""
Say "======================================================================"
Say " Done. Your game is now reachable at:  https://$Domain"
Say ""
Say " Start it with:  cloudflared tunnel run $TunnelName"
Say " (the serve-tailscale.ps1 supervisor picks this up automatically --"
Say "  it starts cloudflared too whenever $ConfFile exists,"
Say "  and writes the public URL into public-url.txt)"
Say ""
Say " Note: the first request after a cold start can take ~10s while the"
Say " certificate is issued. Open https://$Domain once and wait."
Say "======================================================================"
